#!/usr/bin/env bash
set -euo pipefail
BUNDLE_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
DCG_HOME="$BUNDLE_ROOT/dcg"
WORKSPACE="$BUNDLE_ROOT/workspace"
STATE_ROOT="$WORKSPACE/state"

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
require_command() { command -v "$1" >/dev/null 2>&1 || die "Required command is missing: $1"; }
require_java21() {
  require_command java
  java -version 2>&1 | head -n 1 | grep -Eq 'version "21[."]' || die 'Java 21 is required.'
}
compose() {
  if docker compose version >/dev/null 2>&1; then docker compose "$@"; return; fi
  if command -v podman-compose >/dev/null 2>&1; then podman-compose "$@"; return; fi
  die 'Install Docker Compose v2 or podman-compose.'
}
load_database_env() {
  [[ -f "$BUNDLE_ROOT/docker/.env" ]] || die 'Database environment is missing. Run scripts/database-up.sh.'
  set -a
  # Generated by database-up.sh; values contain hexadecimal characters only.
  source "$BUNDLE_ROOT/docker/.env"
  set +a
}
